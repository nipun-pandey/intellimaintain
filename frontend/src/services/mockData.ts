export function generateInitialTelemetry(equipmentId: number, count = 30): Telemetry[] {
  const points: Telemetry[] = [];
  const now = Date.now();
  const isFan = equipmentId === 4;
  const isComp = equipmentId === 2;

  for (let i = count - 1; i >= 0; i--) {
    const timestamp = new Date(now - i * 60 * 1000).toISOString();
    let temp = 54.0 + (Math.sin(i / 3) * 2.0);
    let vib = 2.1 + (Math.cos(i / 4) * 0.3);
    const press = 3.4 + (Math.sin(i / 5) * 0.2);
    const curr = 22.0 + (Math.cos(i / 2) * 1.0);
    const rpm = 1485.0 + (Math.sin(i) * 5.0);
    let isAnomaly = false;
    let score = 0.22;

    if (isFan) {
      temp = 89.5 + (Math.sin(i) * 2.0);
      vib = 7.8 + (Math.cos(i) * 0.8);
      isAnomaly = true;
      score = 0.88;
    } else if (isComp) {
      vib = 5.4 + (Math.cos(i / 2) * 0.4);
      temp = 79.0 + (Math.sin(i / 3) * 1.5);
      isAnomaly = i % 5 === 0;
      score = 0.58;
    }

    points.push({
      id: 1000 + i,
      equipment_id: equipmentId,
      timestamp,
      temperature: Number(temp.toFixed(2)),
      vibration: Number(vib.toFixed(3)),
      pressure: Number(press.toFixed(2)),
      motor_current: Number(curr.toFixed(2)),
      speed_rpm: Number(rpm.toFixed(1)),
      sensor_quality: 'good',
      is_anomaly: isAnomaly,
      anomaly_score: score,
    });
  }
  return points;
}
